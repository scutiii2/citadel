import { expect, test } from '@playwright/test';
import { installFakeApi } from './fakeApi';
import { PROFILE, ownedAscended } from '../src/api/AscensionClient.fixtures';

for (const width of [1440, 768, 375]) {
  test(`three modes retain header and preview cards at ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height:1000 });
    const api = await installFakeApi(page);
    api.ascension.profile = { ...structuredClone(PROFILE), ascendeds:[ownedAscended('guardian', {overall:720}),ownedAscended('striker')],squad:['guardian','striker'] };
    await page.goto('/#ticket=e2e-launch');
    await page.getByRole('tab', {name:'Battle',exact:true}).click();
    await expect(page.getByRole('heading',{name:'Choose your path'})).toBeVisible();
    await page.screenshot({path:testInfo.outputPath('mode-hub.png'),fullPage:true});
    await page.getByRole('button',{name:'Explore hunts',exact:true}).click();
    await page.getByRole('button',{name:/Frontier Recommended/}).click();
    await expect(page.getByText(/20% fewer XP/)).toBeVisible();
    await page.screenshot({path:testInfo.outputPath('hunts.png'),fullPage:true});
    await page.getByRole('button',{name:'← All modes'}).click();
    await page.getByRole('button',{name:'View trials'}).click();
    await expect(page.getByRole('button',{name:'Pure',exact:true})).toBeVisible();
    await page.getByRole('button',{name:'Pure',exact:true}).click();
    await expect(page.getByText('No eligible Ascended')).toBeVisible();
    await page.getByRole('button',{name:'Enchant',exact:true}).click();
    await expect(page.getByText('First-clear rewards ×2',{exact:false})).toBeVisible();
    const card=page.locator('.squad-face').first(); await expect(card).toBeVisible();
    await expect(card.locator('img.portrait')).toHaveAttribute('src','/ascended/guardian/sprite_battle.webp');
    expect((await card.boundingBox())!.width).toBeGreaterThanOrEqual(160);
    await page.screenshot({path:testInfo.outputPath('trials.png'),fullPage:true});
    await page.getByRole('button',{name:'← All modes'}).click();
    await page.getByRole('button',{name:'Plan expedition'}).click();
    await page.getByRole('button',{name:'4 hours',exact:true}).click();
    await expect(page.getByText(/Expected rewards: 400 XP/)).toBeVisible();
    await page.getByRole('button',{name:'Send on expedition'}).click();
    await expect(page.getByRole('button',{name:'Claim & Return'})).toBeDisabled();
    await expect(page.locator('.expedition-active .portrait')).toHaveAttribute('src','/ascended/guardian/sprite_battle.webp');
    await page.screenshot({path:testInfo.outputPath('expedition.png'),fullPage:true});
    await page.getByRole('tab',{name:'Collection',exact:true}).click();
    await page.getByRole('button',{name:'Guardian, Common, level 3',exact:true}).click();
    await expect(page.getByRole('dialog')).toContainText('On expedition');
    await expect(page.getByRole('button',{name:'Add to squad',exact:true})).toBeDisabled();
    await page.getByRole('button',{name:'Close',exact:true}).click();
    api.expedition!.ends_at=Date.now()/1000-1;
    await page.goto('/?reopen=1#ticket=e2e-launch');
    await page.getByRole('tab',{name:'Battle',exact:true}).click();
    await page.getByRole('button',{name:'Plan expedition'}).click();
    await expect(page.getByRole('button',{name:'Claim & Return'})).toBeEnabled();
    await page.getByRole('button',{name:'Claim & Return'}).click();
    await expect(page.getByText(/Returned with 400 XP and 100 Insignia/)).toBeVisible();
    expect((api.ascension.profile as unknown as typeof PROFILE).squad).toEqual(['striker']);
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await expect(page.locator('.mast .brand-icon')).toBeVisible();
    expect(api.unexpected).toEqual([]);
  });
}
